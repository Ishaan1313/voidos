"""
modules/envschema.py — turns "first setup/.env.example" into a list of settings a form can show.

The example file is the single list of every .env setting, each with a comment that explains it.
The setup wizard reads it through here, so the wizard always asks for exactly what the file lists:
add a setting to the example and the wizard asks for it, with no second list to keep in step.

Standard library only (the installer can import it before packages are installed).

  load(example_path)    -> {"groups": [{"id", "title", "basic", "settings": [setting, ...]}, ...]}
  validate(setting, v)  -> (clean_value, error)

A setting is {key, label, help, type, options, default, placeholder, secret, inline}:
  type is "bool" (true/false), "int", "choice" (options) or "text".
"""
