# Shown in the first step, with the Essentials, because everyone sets them.
BASIC_EXTRA = ("VOID_FILE_ROOT", "VOID_APP_DATA_DIR")

_SECTION = re.compile(r"^#\s*──\s*(.+?)\s*─+\s*$")
_SETTING = re.compile(r"^(#\s*)?([A-Za-z][A-Za-z0-9_]*)=(.*)$")


def _split(rest: str):
    """'value   # note' -> ('value', 'note'). Quoted values are kept whole."""
    rest = rest.rstrip()
    if rest[:1] in ("'", '"'):
        q = rest[0]
        end = rest.find(q, 1)
        if end != -1:
            tail = rest[end + 1:]
            return rest[: end + 1], (tail.strip().lstrip("#").strip() if "#" in tail else "")
    m = re.search(r"\s+#\s*", rest)
    if m:
        return rest[: m.start()].strip(), rest[m.end():].strip()
    return rest.strip(), ""


def _label(key: str) -> str:
    if key in LABELS:
        return LABELS[key]
    words = re.sub(r"^(VOID|CF)_", "", key).split("_")
    small = {"MB": "MB", "IP": "IP", "ID": "ID", "URL": "URL", "TTL": "TTL", "WEBDAV": "WebDAV", "UI": "UI", "S": "(s)"}
    out = [small.get(w, w.capitalize()) for w in words]
    return " ".join(out)


def _kind(key: str, default: str):
    if key in CHOICES:
        return "choice", CHOICES[key]
    if default.lower() in ("true", "false"):
        return "bool", None
    if re.fullmatch(r"\d+", default):
        return "int", None
    return "text", None


def load(example_path: str) -> dict:
    try:
        with open(example_path, encoding="utf-8") as f:
            lines = [ln.rstrip("\n") for ln in f]
    except OSError:
        return {"groups": []}
    groups, cur, block, seen = [], None, [], set()
    for raw in lines:
        s = raw.strip()
        m = _SECTION.match(s)
        if m:
            cur = {"id": re.sub(r"[^a-z0-9]+", "-", m.group(1).lower()).strip("-"), "title": m.group(1),
                   "basic": m.group(1).lower() == "essentials", "settings": []}
            groups.append(cur)
            block = []
            continue
        if not s:
            block = []
            continue
        sm = _SETTING.match(s)
        if sm and cur is not None:
            key = sm.group(2)
            if key in seen or key in SKIP_KEYS:
                continue
            seen.add(key)
            default, inline = _split(sm.group(3))
            if default[:1] in ("'", '"') and default[-1:] == default[:1] and len(default) >= 2:
                default = default[1:-1]
            placeholder = ""
            if ("<" in default and ">" in default) or key in EXAMPLE_ONLY:   # e.g. <VOID_FILE_ROOT>/app-data
                placeholder, default = default, ""
            kind, options = _kind(key, default)
            text = " ".join(block).strip()
            help_ = " ".join(p for p in (text, inline) if p) or HELP_FALLBACK.get(key, "")
            cur["settings"].append({
                "key": key, "label": _label(key), "help": help_, "type": kind,
                "options": ([{"value": o, "label": CHOICE_LABELS.get(o, o)} for o in options] if options else None),
                "default": default, "placeholder": placeholder,
                "secret": bool(re.search(r"SECRET|TOKEN|PASSWORD", key)), "active_in_example": not bool(sm.group(1)),
            })
            continue
        if s.startswith("#"):
            body = s.lstrip("#").strip()
            if not body:
                block = []                      # a bare "#" ends a paragraph
            elif cur is not None:
                block.append(body)
    groups = [g for g in groups if g["settings"]]
    # the first-step extras move out of the Files group
    basic = next((g for g in groups if g["basic"]), None)
    if basic is not None:
        for g in groups:
            if g is basic:
                continue
            for st in list(g["settings"]):
                if st["key"] in BASIC_EXTRA:
                    g["settings"].remove(st)
                    basic["settings"].append(st)
    groups = [g for g in groups if g["settings"]]
    for g in groups:
        if g["basic"]:
            g["title"] = "Basics"
            g["id"] = "basics"
    return {"groups": groups}


def flat(example_path: str) -> dict:
    out = {}
    for g in load(example_path)["groups"]:
        for st in g["settings"]:
            out[st["key"]] = st
    return out


def validate(setting: dict, value) -> tuple:
    """-> (value as it should be written, error text or '')."""
    v = "" if value is None else str(value).strip()
    if any(c in v for c in ("\n", "\r", "\x00")):
        return "", f"{setting['label']}: must be a single line."
    t = setting["type"]
    if t == "bool":
        low = v.lower()
        if low in ("true", "1", "yes", "on"):
            return "true", ""
        if low in ("false", "0", "no", "off"):
            return "false", ""
        return "", f"{setting['label']}: must be on or off."
    if t == "int":
        if not re.fullmatch(r"\d{1,9}", v):
            return "", f"{setting['label']}: must be a whole number (0 or more)."
        return str(int(v)), ""
    if t == "choice":
        allowed = [o["value"] for o in setting["options"] or []]
        if v not in allowed:
            return "", f"{setting['label']}: choose one of {', '.join(a or 'automatic' for a in allowed)}."
        return v, ""
    if len(v) > 600:
        return "", f"{setting['label']}: too long."
    return v, ""
